#==============================================================================
# b5gen_trend_run_gate_1 — 추세 아래 연속 개월수(지속성)로 정하는 총노출 게이트
#                          (표적 칸: action = scalar_exposure · state = trend)
#
# ★기전 (사전 선언 — 특정 시기를 보고 만든 규칙이 아니다)
#   이 계보의 구속 낙폭은 단발 급락이 아니라 여러 해에 걸친 침식이다. 침식은 깊이도 변동성도
#   극단으로 안 가므로 깊이·변동성 계열은 가장 오래 잃는 국면에서 가장 덜 개입한다.
#   지속성 — 시장이 자기 12개월 추세 아래에 **연속으로** 머문 개월수 — 는 침식에서만 자기
#   이력의 극단으로 간다. 이 상태를 보유 안 시장베타 순위로 소비하는 arm(trend_persist_tilt)은
#   이미 있다. 이 arm 은 같은 상태를 **총노출 하나**로 소비한다.
#   짝의 의미: 같은 달·같은 상태에서 배분만 다르다(전 보유 균등 vs 시장베타 순위). 종목 차등이
#   정보를 나르는지는 짝의 차이가 말하고, 타이밍 자체가 정보를 나르는지는 이 arm 의 lag-1·
#   블록 순열 반증이 말한다 — 스칼라라 횡단면 순열 검정이 개입하지 않는다.
#   추세 부호 하나로 전량 현금을 정하는 arm(ts_mom_sign)과의 차이: 저쪽은 부호가 음이면 첫 달부터
#   0 이고, 이쪽은 연속 길이가 자기 이력 중앙을 넘는 만큼만 단계적으로 줄인다 — 짧은 음의 구간은
#   그대로 두고 오래 이어진 구간에서만 깊게 깎는다. 출력은 부호의 단조 변환이 아니라 **경로 길이의
#   함수**다(같은 음의 부호에서 1 과 0 사이 어느 값도 나온다).
#   드물고 오래 이어지는 개입 형태는 한 달 지연에 둔감하고(느린 상태), 무작위 블록 재배치와
#   갈리도록(개입 달이 몇 개의 긴 구간에 몰린다) 의도한 것이다. 반증 조건: 급락 뒤 V자 반등에서는
#   연속 길이가 바닥 이후에도 자라므로 회복 초입을 현금으로 보낸다 — 급락형 바닥에서는 수익
#   손실이 낙폭 감소를 상쇄한다.
#
# ★계약
#   반환 = 스칼라 e ∈ [0,1] (표적이 scalar_exposure 이므로 종목별 표를 내지 않는다).
#   H = 확장창(t 행까지 · 미래 행 없음) · t 행이 미실현인 익월 수익 열은 읽지 않는다.
#   행 s 의 연속 길이는 s 행까지의 정보로만 정해진다(과거 행도 그 시점 PIT 값).
#   임의 상수 금지 — 추세 아래 여부는 엔진 제공 r252 의 부호(0 은 정의 경계), 개입 시작점은
#   연속 길이 자기 이력의 경험분포 중앙. 추정 불가·표본 부족이면 e <- 1(무개입). 오류를 던지지 않는다.
#   외부 데이터 없음 — ctx$hold 도 읽지 않는다(보유 구성과 무관한 순수 시장 상태 층).
#==============================================================================

overlay_expo_b5gen_trend_run_gate_1 <- function(H, t, ctx) {
  nmin <- suppressWarnings(as.integer(ctx$n_min))
  if (length(nmin) != 1L || !is.finite(nmin) || nmin < 12L) nmin <- 24L

  tt <- suppressWarnings(as.integer(t))
  if (length(tt) != 1L || !is.finite(tt)) return(1)
  tt <- min(tt, nrow(H))
  if (tt < nmin) return(1)                     # 경험분포를 세울 이력이 없다

  # ── ① 추세 아래 여부 — 엔진이 주는 r252(후행 252거래일 수익)의 부호. 창 길이를 내가 고르지 않는다.
  r <- suppressWarnings(as.numeric(H$r252))[seq_len(tt)]
  fin <- is.finite(r)
  if (sum(fin) < nmin) return(1)
  below <- fin & r < 0                         # 부호 경계 — 상수 문턱이 아니다

  # ── ② 각 행까지의 연속 개월수 — run[s] 는 s 행까지의 정보만으로 정해진다(전방 누적 없음)
  run <- integer(tt)
  acc <- 0L
  for (s in seq_len(tt)) {
    acc <- if (isTRUE(below[s])) acc + 1L else 0L
    run[s] <- acc
  }
  run_now <- run[tt]
  if (run_now <= 0L) return(1)                 # 추세 위 = 무개입

  # ── ③ 개입 강도 g — 지금 연속 길이가 자기 이력(추세 아래였던 달들)에서 얼마나 긴가.
  #   추세 위 구간은 분포에서 뺀다(0 이 분포를 지배한다). 중앙 위에서만 개입 — 문턱은 데이터가 정한다.
  hist_run <- run[run > 0L]
  if (length(hist_run) < nmin) return(1)
  q <- stats::ecdf(hist_run)(run_now)
  g <- (q - 0.5) / 0.5
  g <- max(0, min(1, g))
  if (g <= 0) return(1)

  # ── ④ 총노출 = 1 − g — 전 보유에 같은 값(배분 균등). 증액은 없다.
  max(0, min(1, 1 - g))
}
