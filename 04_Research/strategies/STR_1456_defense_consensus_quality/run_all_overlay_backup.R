stopifnot(is.data.table(FACTORS), all(c("Date","Ticker","Score") %in% names(FACTORS)), nrow(FACTORS) > 0)
cat("\n[Phase 2] Backtest (N=30, EW, BZ 50/25)...\n")
RAWDATA <- copy(RAWDATA_ORIG)
sim_base <- run_monthly_simulation(RAWDATA=RAWDATA, BM_DT=BM_DT, FACTORS=FACTORS, n_holdings=30L, weight_method="equal", commission=0.0015, buffer_zone=list(keep_n=50L, entry_n=25L))
cat("\n[Phase 3] DD Brake (t-1, start=8%, full=25%)...\n")
raw_ret <- as.numeric(sim_base$strategy_xts); raw_dates <- as.Date(index(sim_base$strategy_xts)); n_f <- length(raw_ret)
nav_dd <- cumprod(1+raw_ret); dd_pct <- 1-nav_dd/cummax(nav_dd)
DD_START <- 8/100; DD_FULL <- 0.25; DD_MIN_EXP <- 0.30
dd_pct_lagged <- c(0, dd_pct[-n_f])
dd_exp_lagged <- fifelse(dd_pct_lagged<=DD_START, 1.0, fifelse(dd_pct_lagged>=DD_FULL, DD_MIN_EXP, pmax(DD_MIN_EXP, 1.0-(dd_pct_lagged-DD_START)/(DD_FULL-DD_START)*(1-DD_MIN_EXP))))
final_ret <- raw_ret * dd_exp_lagged
cat("\n[Phase 4] Final assembly...\n")
combined_xts <- xts(final_ret, order.by=raw_dates); names(combined_xts) <- "Strategy"
sim <- sim_base; sim$strategy_xts <- combined_xts; sim$bm_xts <- sim_base$bm_xts[raw_dates]
sim$DAILY_NAV_DT <- data.table(Date=raw_dates, NAV=cumprod(1+final_ret)*10000, Strategy_Ret=final_ret)
cat("\n[Phase 5] Analysis + Hurdle...\n")
output_dir <- file.path(SCRIPT_DIR, "output"); dir.create(output_dir, showWarnings=FALSE, recursive=TRUE)
perf_strat <- summarise_perf(sim$strategy_xts, "Defense_Cons_Quality"); perf_bm <- summarise_perf(sim$bm_xts, "BM")
cat(sprintf("  %s: CAGR=%.2f%% SR=%.3f MDD=%.1f%%\n", "STR_1456", perf_strat$CAGR, perf_strat$Sharpe, perf_strat$MDD))
generate_charts(sim, output_dir=output_dir, strategy_name="Defense_Cons_Quality")
fwrite(rbind(perf_strat, perf_bm), file.path(output_dir, "performance.csv"))
saveRDS(sim, file.path(output_dir, "sim_result.rds")); saveRDS(sim, file.path(SCRIPT_DIR, "sim_result.rds"))
