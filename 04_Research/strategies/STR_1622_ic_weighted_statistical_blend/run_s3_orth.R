if (!exists("FACTORS") || is.null(FACTORS) || nrow(FACTORS) == 0) {
  stop("FACTORS not generated by factor_engine.R")
}

last_date <- max(FACTORS$Date)
cat(sprintf("Using sig_date: %s | n rows: %d\n", last_date, nrow(FACTORS[Date == last_date])))

new_z <- FACTORS[Date == last_date, setNames(Score, Ticker)]
