cat("Calling compute_factor_orthogonality...\n")
orth <- compute_factor_orthogonality(new_z, last_date, active_only = TRUE)
cat(sprintf("max_corr: %.4f | max_corr_factor: %s | independence: %s | n_compared: %d\n",
            orth$max_corr, orth$max_corr_factor, orth$independence, orth$n_compared))

s3_verdict <- if (orth$independence == "independent") "PASS" else if (orth$independence == "partial") "PASS_PARTIAL" else "FAIL_REDUNDANT"

top5 <- head(orth$pairwise_corr[order(-abs(orth$pairwise_corr$Corr)), ], 5)

s3_artifact <- list(
  strategy_id     = STRATEGY_ID,
  factor_id       = FACTOR_ID,
  stage           = "S3",
  generated_at    = format(Sys.Date()),
  sig_date        = format(last_date),
  max_corr        = round(orth$max_corr, 4),
  max_corr_factor = orth$max_corr_factor,
  independence    = orth$independence,
  n_compared      = orth$n_compared,
  s3_verdict      = s3_verdict,
  top5_corr       = lapply(seq_len(nrow(top5)), function(i)
    list(Factor_Name = top5$Factor_Name[i], Corr = round(top5$Corr[i], 4))),
  note            = "5-factor IC-weighted blend. High overlap expected with STR_1621 due to shared C19+V14+D01 components."
)

out_path <- file.path(STRAT_DIR, "stage_artifacts", sprintf("s3_orthogonality_%s.json", STRATEGY_ID))
write_json(s3_artifact, out_path, auto_unbox = TRUE, pretty = TRUE)
cat(sprintf("S3 artifact written: %s\n", out_path))
cat(sprintf("VERDICT: %s | max_corr=%.4f | independence=%s\n", s3_verdict, orth$max_corr, orth$independence))
