                                  prereg = "stage_artifacts/programs/P1_RETURN/P1R02_1801_long_leg/prereg.json",
                                  prereg_md5 = md5, status = "registered", n_variants = 1L, variants = list("P1R02_LONG")), root = ROOT)
cat("registered P1R02_1801_long_leg · prereg md5", md5, "· engine", pre$engine_md5_at_registration, "· wrapper", pre$wrapper_md5, "\n")
