ROOT <- "C:/Users/99922/OneDrive/Quant_Module_Moltbot"; Sys.setenv(QM_ROOT = ROOT)
suppressPackageStartupMessages(library(jsonlite))
RD  <- file.path(ROOT, "04_Research/programs/P1_RETURN/P1R02_1801_long_leg")
SA  <- file.path(ROOT, "stage_artifacts/programs/P1_RETURN/P1R02_1801_long_leg")
pre <- fromJSON(file.path(RD, "prereg.json"), simplifyVector = FALSE)
if (!is.null(pre$registered_at)) stop("이미 등록됨: ", pre$registered_at)
pre$registered_at <- format(Sys.time(), "%Y-%m-%dT%H:%M:%S%z")
pre$engine_md5_at_registration <- unname(tools::md5sum(file.path(ROOT, "04_Research/strategies/RP_AUTO_CLEAN_1801_01777/engine.R")))
